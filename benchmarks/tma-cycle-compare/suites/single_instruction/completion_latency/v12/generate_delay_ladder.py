#!/usr/bin/env python3
"""Generate V12's immutable, non-adaptive 640-position PTX scan.

The single fixed scan is physically encoded as eighty statically selected
8-position kernel banks.  Host control selects the bank before kernel launch,
outside the timed interval.  Inside a bank, moving one position adds one
predicate, one uniform branch and one retained PM-event: three issued
instructions.  Position 7 uses three PM-events because its selector ends in an
unconditional branch.  Bank N has N*8*3 base PM-events compiled into it.
"""

from pathlib import Path


POINTS = 640
BANK_SIZE = 8
BANKS = POINTS // BANK_SIZE
STEP = 3
OUTPUT = Path(__file__).with_name("delay_ladder_v12.inc")


def quoted(line: str) -> str:
    return '    "' + line.replace('\\', '\\\\').replace('"', '\\"') + '\\n\\t"'


def bank_ladder(bank: int) -> list[str]:
    prefix = f"delay_v12_bank_{bank}"
    ptx = ["{", ".reg .pred delay_v12_slot_pred;"]
    for item in range(bank * BANK_SIZE * STEP):
        ptx.append(f"pmevent {item % 4};")
    for slot in range(BANK_SIZE - 1):
        ptx.extend([
            f"setp.eq.u32 delay_v12_slot_pred, %1, {slot};",
            f"@delay_v12_slot_pred bra.uni {prefix}_slot_{slot};",
        ])
    ptx.append(f"bra.uni {prefix}_slot_{BANK_SIZE - 1};")
    for slot in range(BANK_SIZE - 1, 0, -1):
        ptx.append(f"{prefix}_slot_{slot}:")
        event_count = STEP if slot == BANK_SIZE - 1 else 1
        for item in range(event_count):
            ptx.append(f"pmevent {(slot * STEP + item) % 4};")
    ptx.extend([f"{prefix}_slot_0:", "}"])
    return ptx


def macro(name: str, lines: list[str]) -> str:
    continuation = " " + chr(92) + "\n"
    return (
        f"#define {name} " + chr(92) + "\n"
        + continuation.join(quoted(line) for line in lines)
        + "\n"
    )


def render() -> str:
    total_events = (
        sum(bank * BANK_SIZE * STEP for bank in range(BANKS))
        + BANKS * ((BANK_SIZE - 2) + STEP)
    )
    header = (
        "// Generated by generate_delay_ladder.py; do not edit by hand.\n"
        f"// positions={POINTS}, banks={BANKS}, bank_size={BANK_SIZE}, "
        f"requested_cycles_per_step={STEP}, static_pmevents={total_events}\n"
        f"#define V12_DELAY_LADDER_POINTS {POINTS}\n"
        f"#define V12_DELAY_LADDER_BANKS {BANKS}\n"
        f"#define V12_DELAY_LADDER_BANK_SIZE {BANK_SIZE}\n"
        f"#define V12_DELAY_LADDER_STEP {STEP}\n"
        "#define V12_FOR_EACH_DELAY_BANK(M) "
        + " ".join(f"M({bank})" for bank in range(BANKS))
        + "\n"
    )
    bodies = "".join(
        macro(f"V12_DELAY_BANK_{bank}_PTX", bank_ladder(bank))
        for bank in range(BANKS)
    )
    return header + bodies


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8")
    print(OUTPUT)
